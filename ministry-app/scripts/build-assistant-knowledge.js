/**
 * Writes server/src/instructions.ts from the app's content files, so the
 * AFM Assistant server knows exactly what the app shows.
 * Run after editing content:  node scripts/build-assistant-knowledge.js
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const cache = {};

function load(file) {
  const abs = path.resolve(file);
  if (cache[abs]) return cache[abs].exports;
  const src = fs.readFileSync(abs, 'utf8');
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.React } }).outputText;
  const mod = { exports: {} };
  cache[abs] = mod;
  const req = (id) => {
    if (/\.(png|jpe?g)$/.test(id)) return 0; // images are not needed for text
    if (id === 'react-native') return { Platform: { OS: 'node' } };
    const base = id.startsWith('@/') ? path.join(root, 'src', id.slice(2)) : path.resolve(path.dirname(abs), id);
    for (const ext of ['.ts', '.tsx', '/index.ts']) if (fs.existsSync(base + ext)) return load(base + ext);
    return require(id);
  };
  new Function('module', 'exports', 'require', js)(mod, mod.exports, req);
  return mod.exports;
}

const { buildInstructions } = load(path.join(root, 'src/lib/assistantKnowledge.ts'));
const text = buildInstructions();
const out = `// Generated by scripts/build-assistant-knowledge.js from the app's content. Do not edit by hand.\nexport const INSTRUCTIONS = ${JSON.stringify(text)};\n`;
fs.writeFileSync(path.join(root, 'server/src/instructions.ts'), out);
console.log(`Wrote server/src/instructions.ts (${text.length} characters)`);
